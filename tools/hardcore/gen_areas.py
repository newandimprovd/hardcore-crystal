#!/usr/bin/env python3
"""Hardcore Crystal area generator (stage 5+).

Writes maps, tables, trainers, text pools and flags for the generated areas as plain assembly.
Run after gen_moves.py and gen_roster.py:  python3 tools/hardcore/gen_areas.py
Deterministic: the same inputs always give the same files.
"""
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from areas import a1, emit  # noqa: E402
from areas.model import World, read, write  # noqa: E402
from areas.party import Roster  # noqa: E402
from areas.text import pool_asm  # noqa: E402


def emit_pools(w):
    o = ["; Generated by tools/hardcore/gen_areas.py. Do not edit by hand.\n"]
    for key, kinds in w.pools.items():
        o.append(f'SECTION "Area Text {key}", ROMX\n')
        for kind, label in (("seen", "HC_SeenText"), ("beaten", "HC_BeatenText"), ("after", "HC_AfterText")):
            o.append(pool_asm(f"{label}_{key}", kinds[kind], key))
        o.append("ENDSECTION\n")
    write("data/hardcore/area_text.asm", "\n".join(o) + "\n")


def patch_extra():
    """Cherrygrove's north exit leads to Tithe Road, Route 29 no longer leads to Route 46."""
    p = "data/maps/attributes.asm"
    s = read(p)
    s = s.replace("\tconnection north, Route30, ROUTE_30, 5\n\tconnection east, Route29, ROUTE_29, 0\n",
                  "\tconnection north, TitheRoad, TITHE_ROAD, 5 ; HC-AREAS\n\tconnection east, Route29, ROUTE_29, 0\n")
    s = s.replace("\tconnection north, Route46, ROUTE_46, 10\n\tconnection west, CherrygroveCity, CHERRYGROVE_CITY, 0\n",
                  "\tconnection west, CherrygroveCity, CHERRYGROVE_CITY, 0 ; HC-AREAS: no way north to Route 46\n")
    write(p, s)
    m = read("main.asm")
    inc = 'INCLUDE "data/hardcore/area_text.asm"\n'
    if inc not in m:
        m = m.replace('INCLUDE "data/hardcore/gen_trainer_data.asm"\n', 'INCLUDE "data/hardcore/gen_trainer_data.asm"\n' + inc, 1)
        write("main.asm", m)


def main():
    rng = random.Random(20261024)
    w = World()
    roster = Roster()
    a1.build(w, roster, rng)
    emit.patch_tree()
    sizes = emit.emit_all(w)
    emit_pools(w)
    patch_extra()
    nm = sum(len(g.maps) for g in w.groups.values())
    nt = sum(len(v) for v in w.trainers.values())
    print(f"groups {len(w.groups)}, maps {nm}, trainers {nt}, flags {len(w.flag_names)}")
    print("trainer bytes", sum(sizes.values()))


if __name__ == "__main__":
    main()
