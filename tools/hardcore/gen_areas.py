#!/usr/bin/env python3
"""Hardcore Crystal area generator (stage 5+).

Writes maps, tables, trainers, text pools and flags for the generated areas as plain assembly.
Run after gen_moves.py and gen_roster.py:  python3 tools/hardcore/gen_areas.py
Deterministic: the same inputs always give the same files.
"""
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from areas import named_text as N  # noqa: E402
from areas import a1, a2, a3, a4, a5, cameos, emit, lore, named, opening, purg, specials, wild  # noqa: E402
from areas.model import ForeignWarp  # noqa: E402
from areas.model import World, read, write  # noqa: E402
from areas.party import Roster  # noqa: E402
from areas.text import pool_asm  # noqa: E402


def emit_pools(w):
    o = ["; Generated by tools/hardcore/gen_areas.py. Do not edit by hand.\n"]
    for key, kinds in w.pools.items():
        o.append(f'SECTION "Area Text {key}", ROMX\n')
        for kind, label in (("seen", "HC_SeenText"), ("beaten", "HC_BeatenText"), ("after", "HC_AfterText")):
            o.append(pool_asm(f"{label}_{key}", kinds[kind], key))
        o.append("ENDSECTION\n")
    write("data/hardcore/area_text.asm", "\n".join(o) + "\n")


def patch_extra():
    """Cherrygrove's north exit leads to the Tithe Junction, Route 29 no longer leads to Route 46."""
    p = "data/maps/attributes.asm"
    s = read(p)
    new = "\tconnection north, TitheJunction, TITHE_JUNCTION, %d ; HC-AREAS\n" % (opening.CHERRY_COL - opening.STEM_A)
    for old in ("\tconnection north, Route30, ROUTE_30, 5\n",
                "\tconnection north, TitheRoad, TITHE_ROAD, 5 ; HC-AREAS\n",
                "\tconnection north, TitheJunction, TITHE_JUNCTION, -1 ; HC-AREAS\n"):
        if old in s:
            s = s.replace(old, new, 1)
            break
    else:
        raise AssertionError("Cherrygrove north connection not found")
    s = s.replace("\tconnection north, Route46, ROUTE_46, 10\n\tconnection west, CherrygroveCity, CHERRYGROVE_CITY, 0\n",
                  "\tconnection west, CherrygroveCity, CHERRYGROVE_CITY, 0 ; HC-AREAS: no way north to Route 46\n")
    write(p, s)
    m = read("main.asm")
    inc = 'INCLUDE "data/hardcore/area_text.asm"\n'
    if inc not in m:
        m = m.replace('INCLUDE "data/hardcore/gen_trainer_data.asm"\n', 'INCLUDE "data/hardcore/gen_trainer_data.asm"\n' + inc, 1)
        write("main.asm", m)


def write_spawns(w):
    """tools/hardcore/spawns.json: where the tests may put the player on every plaza (the Pokecenter door cell, and a street cell)."""
    import json
    out = {}
    for g, m in w.all_maps():
        if hasattr(m, "spawn_cell"):
            e, xo, jr = getattr(m, "street", (3, 3, 4))
            out[m.name] = dict(const=m.const, spawn=list(m.spawn_cell), street=[2 * min(e, xo) + 1, 2 * jr + 1], w=m.w, h=m.h, grass=list(getattr(m, "grass_cell", (0, 0, 0))))
    json.dump(out, open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "spawns.json"), "w"), indent=1, sort_keys=True)


def main():
    rng = random.Random(20261024)
    w = World()
    roster = Roster()
    _, exits = a1.build(w, roster, rng, open_exit=True)
    _, exits = a2.build(w, roster, rng, exits, open_exit=True)
    _, exits = a3.build(w, roster, rng, exits, open_exit=True)
    a4.build(w, roster, rng, exits, open_exit=True)  # its last boss room leads into the mansion
    # Area 5 is entered through the portal in the New Bark Town crater (warp 5 of that map, see maps/NewBarkTown.asm)
    a5.build(w, roster, rng, [ForeignWarp("NEW_BARK_TOWN", 5)])
    # the historic characters, placed into the finished areas
    cameos.area1(w, w.groups["AREA1"])
    cameos.area2(w, w.groups["AREA2"], rng, roster)
    named.add_all(w, roster)  # the historic characters of the plazas (key bearers first), then the generic duelists
    for tag, key, cls, texts, size in (("Tithe", "RIVAL1", "RIVAL1", N.RIVAL1, 3), ("Grove", "RIVAL2", "RIVAL1", N.RIVAL2, 4),
                                       ("Axiom", "RIVAL3", "RIVAL2", N.RIVAL3, 4)):  # the rival waits in the stem of plaza 2
        named.plaza_rival(w, w.groups[named.AREA_OF[tag]], f"{tag}Plaza2", key, cls, named.level_at(tag, 2) + 2, size,
                          random.Random("named-" + key), roster, texts, cameos.find, cameos.add_sprite)
    specials.add_all(w, roster, random.Random(20261112))  # the named duelists, with a random source of their own
    # the opening junction outside Cherrygrove (Mr. Pokemon, Joyce, the door to Purgatorio) and Purgatorio itself
    _, cave, junction = opening.build(w, roster, rng)
    road = next(m for m in w.groups["AREA1"].maps if m.name == "TitheRoad")
    junction.connections["north"] = (road, junction.a - road.a)
    road.connections["south"] = (junction, road.a - junction.a)

    class Cherry:
        name, const = "CherrygroveCity", "CHERRYGROVE_CITY"
    junction.connections["south"] = (Cherry, opening.STEM_A - opening.CHERRY_COL)
    purg.build(w, roster, rng, w.purg_doors, cave)
    write_spawns(w)
    lore.emit(w)
    emit.patch_tree()
    wild.build(w, roster)
    sizes = emit.emit_all(w)
    emit_pools(w)
    patch_extra()
    nm = sum(len(g.maps) for g in w.groups.values())
    nt = sum(len(v) for v in w.trainers.values())
    print(f"groups {len(w.groups)}, maps {nm}, trainers {nt}, flags {len(w.flag_names)}")
    print("trainer bytes", sum(sizes.values()))


if __name__ == "__main__":
    main()
