"""Writes everything a World contains: constants, tables, map files, trainer banks and flags."""
import os
import re

from .model import ROOT, read, write

HEADER = "; Generated by tools/hardcore/gen_areas.py. Do not edit by hand.\n"


def emit_constants(w):
    o = [HEADER]
    first_group = 27
    for gi, (key, g) in enumerate(w.groups.items()):
        o.append(f"\tnewgroup {key:<20} ; {first_group + gi}")
        for i, m in enumerate(g.maps, 1):
            o.append(f"\tmap_const {m.const + ',':<40} {m.w:2d}, {m.h:2d} ; {i:2d}")
        o.append("\tendgroup\n")
    write("constants/area_map_constants.asm", "\n".join(o) + "\n")


def emit_lists(w):
    ptr = [HEADER]
    lists = [HEADER]
    for key, g in w.groups.items():
        ptr.append(f"\tdw MapGroup_{g.camel:<20} ; {key}")
        lists.append(f"MapGroup_{g.camel}:")
        lists.append("\ttable_width MAP_LENGTH")
        for m in g.maps:
            lists.append(f"\tmap {m.name}, {m.tileset}, {m.env}, {m.landmark}, {m.music}, FALSE, {m.pal}, {m.fish}")
        lists.append(f"\tassert_table_length NUM_{key}_MAPS\n")
    write("data/maps/area_group_pointers.asm", "\n".join(ptr) + "\n")
    write("data/maps/area_map_lists.asm", "\n".join(lists) + "\n")


def emit_data(w):
    """Attributes, blocks and script sections, one file."""
    o = [HEADER, 'SECTION "Area Attributes", ROMX\n']
    for g, m in w.all_maps():
        o.append(f"\tmap_attributes {m.name}, {m.const}, ${m.border:02x}")
        for d in ("north", "south", "west", "east"):
            if d in m.connections:
                t, off = m.connections[d]
                o.append(f"\tconnection {d}, {t.name}, {t.const}, {off}")
        o.append("")
    o.append("ENDSECTION\n")
    for key, g in w.groups.items():
        o.append(f'SECTION "{g.camel} Blocks", ROMX\n')
        for m in g.maps:
            o.append(f'{m.name}_Blocks:\n\tINCBIN "maps/gen/{m.name}.blk"\n')
        o.append("ENDSECTION\n")
    for key, g in w.groups.items():
        for m in g.maps:
            o.append(f'SECTION "{m.name} Scripts", ROMX\n\nINCLUDE "maps/gen/{m.name}.asm"\n\nENDSECTION\n')
    write("data/maps/area_data.asm", "\n".join(o) + "\n")
    # per map files
    for g, m in w.all_maps():
        write(f"maps/gen/{m.name}.asm", HEADER + m.asm())
        write(f"maps/gen/{m.name}.blk", bytes(m.blocks), binary=True)


def emit_flags(w):
    o = [HEADER]
    for name, idx in w.flag_names:
        o.append(f"DEF {name} EQU {idx}")
    write("constants/area_event_flags.asm", "\n".join(o) + "\n")


def emit_group_tables(w):
    roofs = [HEADER]
    sgb = [HEADER]
    sp_ptr = [HEADER]
    sp_lists = [HEADER]
    for key, g in w.groups.items():
        roofs.append(f"\tdb {g.roof if isinstance(g.roof, int) else g.roof} ; {key}")
        sgb.append(f"\tdb {g.sgb} ; {key}")
        sp_ptr.append(f"\tdw {g.camel}GroupSprites")
        sp_lists.append(f"{g.camel}GroupSprites:")
        sprites = list(g.sprites)
        assert len(sprites) <= 23, (key, len(sprites))
        sprites += ["SPRITE_NONE"] * (23 - len(sprites))
        for s in sprites:
            sp_lists.append(f"\tdb {s}")
        sp_lists.append("")
    write("data/maps/area_roofs.asm", "\n".join(roofs) + "\n")
    write("data/maps/area_sgb_roof_pal_inds.asm", "\n".join(sgb) + "\n")
    write("data/maps/area_outdoor_sprite_pointers.asm", "\n".join(sp_ptr) + "\n")
    write("data/maps/area_outdoor_sprites.asm", "\n".join(sp_lists) + "\n")


def emit_roof_pals(w):
    from art import areapal
    areapal.emit(os.path.join(ROOT, "gfx/tilesets/area_bg.pal"))
    areapal.emit_npc(os.path.join(ROOT, "gfx/overworld/area_npc.pal"))
    o = [HEADER]
    for gi, (key, g) in enumerate(w.groups.items()):
        a, b = areapal.roof_colors(key) if key in areapal.AREAS else g.roofpal
        o.append(f"; group {27 + gi} ({key})")
        o.append(f"\tRGB {a[0]:02d},{a[1]:02d},{a[2]:02d}, {a[3]:02d},{a[4]:02d},{a[5]:02d} ; morn/day")
        o.append(f"\tRGB {b[0]:02d},{b[1]:02d},{b[2]:02d}, {b[3]:02d},{b[4]:02d},{b[5]:02d} ; nite\n")
    write("gfx/tilesets/area_roofs.pal", "\n".join(o) + "\n")


def emit_spawns(w):
    c = [HEADER]
    t = [HEADER]
    for const, m, x, y in w.spawns:
        c.append(f"\tconst SPAWN_{const}")
        t.append(f"\tspawn {m.const}, {x:2d}, {y:2d}")
    write("constants/area_spawn_constants.asm", "\n".join(c) + "\n")
    write("data/maps/area_spawn_points.asm", "\n".join(t) + "\n")


def emit_landmarks(w):
    c = [HEADER]
    t = [HEADER]
    n = [HEADER]
    for const, x, y, name in w.landmarks:
        c.append(f"\tconst LANDMARK_{const}")
        label = "".join(p.title() for p in const.split("_")) + "Name"
        t.append(f"\tlandmark {x:3d}, {y:3d}, {label}")
        n.append(f'{label}: db "{name}@"')
    write("constants/area_landmark_constants.asm", "\n".join(c) + "\n")
    write("data/maps/area_landmarks.asm", "\n".join(t) + "\n")
    write("data/maps/area_landmark_names.asm", "\n".join(n) + "\n")


def emit_marts(w):
    c = [HEADER]
    p = [HEADER]
    d = [HEADER]
    for const, label, items in w.marts:
        c.append(f"\tconst MART_{const}")
        p.append(f"\tdw {label}")
        d.append(f"{label}:")
        d.append(f"\tdb {len(items)}")
        for it in items:
            d.append(f"\tdb {it}")
        d.append("\tdb -1 ; end\n")
    write("constants/area_mart_constants.asm", "\n".join(c) + "\n")
    write("data/items/area_mart_pointers.asm", "\n".join(p) + "\n")
    write("data/items/area_marts.asm", "\n".join(d) + "\n")


def emit_trainers(w):
    classes = w.classes
    by_class = {}
    for cls, lst in w.trainers.items():
        recs = []
        for name, party in lst:
            assert 1 <= len(party) <= 6
            s = f'\tdb "{name}@"\n'
            s += "".join(f"\tdb {lv}, {sp}\n" for lv, sp in party)
            s += "\tdb -1\n"
            size = len(name) + 1 + 2 * len(party) + 1
            recs.append((s, size))
        by_class[cls] = recs
    # pack classes into sections of at most 15000 bytes
    sections, cur, cur_size = [], [], 0
    for cls in sorted(by_class, key=lambda c: classes[c]):
        size = sum(r[1] for r in by_class[cls])
        assert size <= 15000, cls
        if cur_size + size > 15000:
            sections.append(cur)
            cur, cur_size = [], 0
        cur.append(cls)
        cur_size += size
    if cur:
        sections.append(cur)
    o = [HEADER]
    for i, sec in enumerate(sections, 1):
        o.append(f'SECTION "Gen Trainers {i}", ROMX\n')
        for cls in sec:
            o.append(f"HC_GenGroup_{cls}:")
            o.append("".join(r[0] for r in by_class[cls]))
        o.append("ENDSECTION\n")
    write("data/hardcore/gen_trainer_data.asm", "\n".join(o) + "\n")
    t = [HEADER, "HC_GenGroupTable:", "\ttable_width 3"]
    for cls, idx in classes.items():
        if cls in by_class:
            t.append(f"\tdb BANK(HC_GenGroup_{cls})\n\tdw HC_GenGroup_{cls} ; {idx} {cls}")
        else:
            t.append(f"\tdb 0\n\tdw 0 ; {idx} {cls}")
    t.append("\tassert_table_length NUM_TRAINER_CLASSES")
    write("data/hardcore/gen_trainer_table.asm", "\n".join(t) + "\n")
    return {cls: sum(r[1] for r in recs) for cls, recs in by_class.items()}


def emit_story(w):
    o = [HEADER, "HC_StoryBosses:"]
    for cls, tid, kind in w.story:
        o.append(f"\tdb {cls}, {tid}, {kind}")
    o.append("\tdb -1")
    write("data/hardcore/story_bosses.asm", "\n".join(o) + "\n")


def emit_all(w):
    emit_constants(w)
    emit_lists(w)
    emit_data(w)
    emit_flags(w)
    emit_group_tables(w)
    emit_roof_pals(w)
    emit_spawns(w)
    emit_landmarks(w)
    emit_marts(w)
    emit_story(w)
    return emit_trainers(w)


# ---------------------------------------------------------------- one-time patches of vanilla tables

MARK = "; HC-AREAS"


def _patch(path, anchor, insert, before=True, count=1):
    s = read(path)
    if insert.strip() in s:
        return
    assert anchor in s, (path, anchor)
    idx = s.index(anchor)
    if before:
        s = s[:idx] + insert + s[idx:]
    else:
        s = s[:idx + len(anchor)] + insert + s[idx + len(anchor):]
    write(path, s)


def _append(path, insert):
    s = read(path)
    if insert.strip() in s:
        return
    write(path, s.rstrip("\n") + "\n\n" + insert)


