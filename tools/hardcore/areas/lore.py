"""The CORKBOARD: a key item that prints the note of every character the player has met, and the endings' lore flags.
Writes data/hardcore/corkboard.asm (included once in the 'Hardcore Story' section of main.asm)."""
from . import cast_text as C
from . import named_text as N
from .flags import flag_once
from .model import write
from .text import Text

HEADER = "; Generated by tools/hardcore/gen_areas.py (areas/lore.py). Do not edit by hand.\n"


TITLES = {  # the line each page has in the list of the board (at most 15 characters)
    "MRP": "MR. POKéMON", "JOYCE": "JOYCE", "BEETLE": "THE BEETLE", "SATOSHI": "SATOSHI",
    "STEINER": "STEINER I", "STEINER2": "STEINER II", "STEINER3": "STEINER III", "STEINER4": "STEINER IV",
    "CROWLEY": "CROWLEY I", "AMPH": "CROWLEY II", "SABBAH": "SABBAH I", "SABBAH2": "SABBAH II",
    "CIORAN": "CIORAN I", "CIORAN2": "CIORAN II", "SUHRAWARDI": "SUHRAWARDI", "QADI": "ABD JABBAR", "SADRA": "SADRA",
    "BRUNO": "BRUNO", "GRAVE": "THE GRAVE", "CAPREAL": "THE POST", "TRUMPET": "THE TRUMPET",
}

# The page code (alpha 3.2, playtest point 9): the board is a full screen list of every page, the ones not pinned yet shown as blanks (Joyce says
# the empty spaces are the interesting ones); A reads a page, B leaves.  Built on ScrollingMenu like the box list of Bill's PC.
PAGE_CODE = """
HC_CorkboardOpen::
	xor a
	ld [wMenuScrollPosition], a
	ret

HC_CorkCount:
; a = how many of the HC_CORK_NOTES pages are pinned
	xor a
	ld [wTextDecimalByte], a
	ld hl, HC_CorkTable
	ld a, HC_CORK_NOTES
.count
	push af
	ld e, [hl]
	inc hl
	ld d, [hl]
	inc hl
	inc hl
	inc hl
	push hl
	ld b, CHECK_FLAG
	call EventFlagAction
	ld a, c
	and a
	jr z, .no
	ld hl, wTextDecimalByte
	inc [hl]
.no
	pop hl
	pop af
	dec a
	jr nz, .count
	ld a, [wTextDecimalByte]
	ret

HC_CorkboardPage::
; wScriptVar = the page chosen (1 .. HC_CORK_NOTES + 1), 0 when the player left the board
	call LoadStandardMenuHeader
	call ClearSprites ; the player and the people of the map must not show through the page
	hlcoord 0, 0
	ld bc, SCREEN_AREA
	ld a, ' '
	call ByteFill
	hlcoord 0, 0
	lb bc, 1, 18
	call Textbox
	hlcoord 1, 1
	ld de, HC_CorkTitle
	call PlaceString
	call HC_CorkCount
	ld [wTextDecimalByte], a
	hlcoord 11, 1
	ld de, wTextDecimalByte
	lb bc, 1, 2
	call PrintNum
	hlcoord 13, 1
	ld de, HC_CorkPinned
	call PlaceString
	hlcoord 0, 3
	lb bc, 13, 18
	call Textbox
	ld hl, HC_CorkMenuHeader
	call CopyMenuHeader
	call ScrollingMenu
	ld a, [wMenuJoypad]
	cp PAD_B
	jr z, .cancel
	ld a, [wMenuSelection]
	jr .done
.cancel
	xor a
.done
	ld [wScriptVar], a
	call CloseWindow
	ret

HC_CorkMenuHeader:
	db MENU_BACKUP_TILES ; flags
	menu_coords 1, 4, 18, 16
	dw .MenuData
	db 1 ; default option

.MenuData:
	db SCROLLINGMENU_DISPLAY_ARROWS ; flags
	db 6, 0 ; rows, columns
	db SCROLLINGMENU_ITEMS_NORMAL ; item format
	dba .Pages
	dba HC_CorkPrint
	dba NULL
	dba NULL

.Pages:
	db HC_CORK_NOTES + 1
for x, HC_CORK_NOTES + 1
	db x + 1
endr
	db -1

HC_CorkPrint:
	push de
	ld a, [wMenuSelection]
	cp HC_CORK_NOTES + 1
	jr z, .whole
	dec a
	ld hl, HC_CorkTable
	ld bc, 4
	call AddNTimes
	ld e, [hl]
	inc hl
	ld d, [hl]
	inc hl
	push hl
	ld b, CHECK_FLAG
	call EventFlagAction
	pop hl
	ld a, c
	and a
	jr z, .blank
	ld e, [hl]
	inc hl
	ld d, [hl]
	jr .print
.whole
	call HC_CorkCount
	cp HC_CORK_NOTES
	ld de, HC_CorkWhole
	jr z, .print
.blank
	ld de, HC_CorkBlank
.print
	pop hl
	call PlaceString
	ret

HC_CorkTitle: db "CORKBOARD@"
HC_CorkPinned: db "/{n}@"
HC_CorkBlank: db "- - - - - - -@"
HC_CorkWhole: db "THE WHOLE BOARD@"
"""


def emit(w):
    keys = list(C.NOTES)
    flags = {k: flag_once(w, f"EVENT_LORE_{k}") for k in keys}
    n = len(keys)
    o = [HEADER, f"DEF HC_CORK_NOTES EQU {n}", "", "HC_CorkTable:"]
    for k in keys:
        o.append(f"\tdw {flags[k]}, HC_CorkT_{k}")
    for k in keys:
        o.append(f'HC_CorkT_{k}: db "{TITLES[k]}@"')
    o.append(PAGE_CODE.replace("{n}", str(n)))
    # the script: the list again and again until B; a page that is not pinned yet says so
    o += ["CorkboardScript::", "\tcallasm HC_CorkboardOpen", ".page", "\tcallasm HC_CorkboardPage", "\tifequal 0, .done"]
    for i, k in enumerate(keys):
        o.append(f"\tifequal {i + 1}, .n{k}")
    o.append(f"\tifequal {n + 1}, .whole")
    o += ["\tsjump .done", ""]
    for k in keys:
        o += [f".n{k}:", f"\tcheckevent {flags[k]}", "\tiffalse .empty", "\topentext", f"\twritetext CorkNote_{k}", "\twaitbutton",
              "\tclosetext", "\tsjump .page", ""]
    # the last page: only when every other page is pinned (the philosophers are optional, so this is the 100% reward)
    o.append(".whole:")
    for k in keys:
        o += [f"\tcheckevent {flags[k]}", "\tiffalse .empty"]
    o += ["\topentext", "\twritetext CorkNote_FULL", "\twaitbutton", "\tclosetext", "\tsjump .page", ""]
    o += [".empty:", "\topentext", "\twritetext CorkEmptyText", "\twaitbutton", "\tclosetext", "\tsjump .page", ".done:", "\tend", ""]
    o.append(Text("Nothing is pinned here yet. Joyce says the empty spaces are the interesting ones.").emit("CorkEmptyText"))
    for k in keys:
        o.append(Text(C.NOTES[k]).emit(f"CorkNote_{k}"))
    o.append(Text(N.FULL_BOARD).emit("CorkNote_FULL"))
    # the endings
    for k in ("EVENT_PURG_NICK", "EVENT_ABYSS_GRAVE_READ", "EVENT_HC_TRUE_END"):
        flag_once(w, k)
    o.append(Text(C.TRUMPET_TRUE).emit("HC_TrumpetText"))
    o.append(Text(
        "Far away, in a cave that is not called Purgatorio any more, Nick puts down a very old book and smiles. "
        "He has the strange feeling he is expected. He is not wrong.\n\n"
        "THE TRUE ENDING. You went down to the grave and up to the fire. Everyone you killed is still dead. "
        "Everyone who was not killed is still arguing. Both are the human condition, and both are fine.").emit("HC_TrueEndText"))
    write("data/hardcore/corkboard.asm", "\n".join(o) + "\n")
