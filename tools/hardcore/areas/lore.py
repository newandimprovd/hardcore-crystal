"""The CORKBOARD: a key item that prints the note of every character the player has met, and the endings' lore flags.
Writes data/hardcore/corkboard.asm (included once in the 'Hardcore Story' section of main.asm)."""
from . import cast_text as C
from .flags import flag_once
from .model import write
from .text import Text

HEADER = "; Generated by tools/hardcore/gen_areas.py (areas/lore.py). Do not edit by hand.\n"


def emit(w):
    keys = list(C.NOTES)
    o = [HEADER, "CorkboardScript::", "\topentext", "\twritetext CorkboardIntroText", "\twaitbutton"]
    for k in keys:
        f = flag_once(w, f"EVENT_LORE_{k}")
        o += [f"\tcheckevent {f}", f"\tiffalse .skip_{k}", f"\twritetext CorkNote_{k}", "\twaitbutton", f".skip_{k}:"]
    o += ["\tclosetext", "\tend", ""]
    o.append(Text("CORKBOARD. Pages pinned so far. Joyce says the empty spaces are the interesting ones.").emit("CorkboardIntroText"))
    for k in keys:
        o.append(Text(C.NOTES[k]).emit(f"CorkNote_{k}"))
    # the endings
    for k in ("EVENT_PURG_NICK", "EVENT_ABYSS_GRAVE_READ", "EVENT_HC_TRUE_END"):
        flag_once(w, k)
    o.append(Text(C.TRUMPET_TRUE).emit("HC_TrumpetText"))
    o.append(Text(
        "Far away, in a cave that is not called Purgatorio any more, Nick puts down a very old book and smiles. "
        "He has the strange feeling he is expected. He is not wrong.\n\n"
        "THE TRUE ENDING. You went down to the grave and up to the fire. Everyone you killed is still dead. "
        "Everyone who was not killed is still arguing. Both are the human condition, and both are fine.").emit("HC_TrueEndText"))
    write("data/hardcore/corkboard.asm", "\n".join(o) + "\n")
