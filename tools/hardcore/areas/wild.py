"""Wild encounters of the generated areas (stage 9).

Every plaza of the five areas has tall grass (layout.grass_patches).  The player has to be able to catch the base form of every
line, so the 62 base forms are spread over the areas by the area's type theme (a weighted split: early areas get more, because
they are played first) and over the seven plazas of each area by a round robin, so every form gets a likely slot and shows up
in two or more plazas.  Levels
follow the plaza's position in the area's level range.  At night the dark, ghost and poison forms of a plaza move up to the
likely slots.

The areas' landmarks sit above KANTO_LANDMARK, so the engine looks wild data up in KantoGrassWildMons: the generated entries are
included in place of data/wild/kanto_grass.asm.  tools/hardcore/wild_out.json records what was generated for the checker
(test_wild.py) and docs/WILD.md lists it for humans."""
import json
import os

from .model import ROOT, write

SLOT_PERCENT = [30, 30, 20, 10, 5, 4, 1]  # engine's GrassMonProbTable (data/wild/probabilities.asm)
CAPACITY = [16, 16, 12, 10, 8]  # base forms per area (62 in all): the early areas are where the player builds a team
RATE = 20  # percent per step in tall grass
NOCTURNAL = {"DARK", "GHOST", "POISON"}
LEVEL_OFFSETS = [0, 1, -1, 2, 0, 1, 3]

AREA_KEYS = ["AREA1", "AREA2", "AREA3", "AREA4", "AREA5"]


def themes():
    from . import a1, a2, a3, a4, a5
    return [m.Spec.theme for m in (a1, a2, a3, a4, a5)], [(m.Spec.l0, m.Spec.l1) for m in (a1, a2, a3, a4, a5)]


def affinity(types, theme):
    ts = sorted(set(types))
    return sum(theme.get(t, 0.15) for t in ts) / len(ts)


def split_forms(bases, theme_list):
    """Base forms -> list (per area) of constants, by theme affinity with the area capacities."""
    prefs = []
    for m in bases:
        aff = [affinity(m["types"], th) for th in theme_list]
        tot = sum(aff)
        prefs.append([a / tot for a in aff])
    order = sorted(range(len(bases)), key=lambda i: (-max(prefs[i]), bases[i]["const"]))
    cap = list(CAPACITY)
    assert sum(cap) == len(bases), (sum(cap), len(bases))
    out = [[] for _ in theme_list]
    for i in order:
        ranked = sorted(range(len(theme_list)), key=lambda a: -prefs[i][a])
        for a in ranked:
            if cap[a] > 0:
                cap[a] -= 1
                out[a].append(i)
                break
    return out


def plan_area(forms, n_plazas):
    """For every plaza of an area the six main slots (form indices, best slot first).  Round robin over the area's forms: the four
    likely slots (30/30/20/10 percent) go to the forms that have had the fewest likely slots so far, the two unlikely ones (5/4)
    to the forms seen in the fewest plazas, so every form gets at least one likely slot and shows up in two or more plazas."""
    n = len(forms)
    likely = {f: 0 for f in forms}
    seen = {f: 0 for f in forms}
    order = {f: i for i, f in enumerate(forms)}
    plans = []
    for k in range(n_plazas):
        shift = round(k * n / n_plazas)

        def rot(f):
            return (order[f] - shift) % n

        top = sorted(forms, key=lambda f: (likely[f], seen[f], rot(f)))[:4]
        rest = sorted((f for f in forms if f not in top), key=lambda f: (seen[f], rot(f)))[:2]
        for f in top:
            likely[f] += 1
        for f in top + rest:
            seen[f] += 1
        plans.append(top + rest)
    return plans


def build(w, roster):
    theme_list, levels = themes()
    bases = [m for m in roster.mons if m["stage"] == 1]
    assert len(bases) == sum(CAPACITY), len(bases)
    split = split_forms(bases, theme_list)
    entries = []  # dicts for the json/doc
    out_asm = ["; Generated by tools/hardcore/areas/wild.py. Do not edit by hand.", "; Replaces data/wild/kanto_grass.asm (see areas/emit.py).",
               "", "KantoGrassWildMons:", ""]
    for a, key in enumerate(AREA_KEYS):
        l0, l1 = levels[a]
        maps = [m for g in w.groups.values() if g.key == key for m in g.maps if getattr(m, "grass", 0)]
        maps.sort(key=lambda m: m.order if hasattr(m, "order") else 0)
        names = [m.name for m in maps]
        n = len(maps)
        forms = split[a]
        # order the forms inside the area by affinity so the best fits come first in the rotation
        forms = sorted(forms, key=lambda i: (-affinity(bases[i]["types"], theme_list[a]), bases[i]["const"]))
        plans = plan_area(forms, n)
        for k, m in enumerate(maps):
            lc = l0 + (l1 - 1 - l0) * k / max(1, n - 1)
            main = plans[k]
            # the rare slot: the best fit of the next area (or a form of this area that is not in the plaza)
            nxt = split[(a + 1) % len(split)]
            rare = nxt[k % len(nxt)] if a < len(split) - 1 else forms[(k + 6) % len(forms)]
            day = main + [rare]
            nite = sorted(main, key=lambda i: 0 if NOCTURNAL & set(bases[i]["types"]) else 1)  # stable: keeps the day order
            nite = nite + [rare]
            lv = [max(2, int(round(lc)) + off) for off in LEVEL_OFFSETS]
            entries.append(dict(area=a + 1, map=m.name, const=m.const, level=round(lc, 1),
                                morn=[[lv[j], bases[day[j]]["const"]] for j in range(7)],
                                day=[[lv[j], bases[day[j]]["const"]] for j in range(7)],
                                nite=[[lv[j], bases[nite[j]]["const"]] for j in range(7)],
                                rate=RATE))
            out_asm.append(f"\tdef_grass_wildmons {m.const}")
            out_asm.append(f"\tdb {RATE} percent, {RATE} percent, {RATE} percent ; encounter rates: morn/day/nite")
            for label, seq in (("morn", day), ("day", day), ("nite", nite)):
                out_asm.append(f"\t; {label}")
                for j in range(7):
                    out_asm.append(f"\tdb {lv[j]}, {bases[seq[j]]['const']}")
            out_asm.append("\tend_grass_wildmons")
            out_asm.append("")
    out_asm.append("\tdb -1 ; end")
    write("data/hardcore/gen_wild_grass.asm", "\n".join(out_asm) + "\n")
    write("tools/hardcore/wild_out.json", json.dumps(dict(slots=SLOT_PERCENT, entries=entries,
                                                         forms=[[bases[i]["const"] for i in f] for f in split]), indent=1))
    doc(entries, bases, split)
    return entries


def doc(entries, bases, split):
    o = ["# Wild encounters", "",
         "Generated by `tools/hardcore/areas/wild.py` (do not edit). Every plaza of the five areas has two tall-grass patches. "
         "The seven slots roll 30/30/20/10/5/4/1 percent; the last one is a visitor from the next area. At night the dark, ghost "
         "and poison forms move up. Encounter rate is %d percent per step in grass." % RATE, ""]
    for a, f in enumerate(split):
        o.append(f"## Area {a + 1}: {len(f)} base forms")
        o.append("")
        o.append(", ".join(sorted(bases[i]["const"] for i in f)))
        o.append("")
        o.append("| Plaza | Level | Day slots (30/30/20/10/5/4/1) |")
        o.append("| --- | --- | --- |")
        for e in entries:
            if e["area"] == a + 1:
                o.append(f"| {e['map']} | {e['level']} | " + ", ".join(f"{s} L{l}" for l, s in e["day"]) + " |")
        o.append("")
    write("docs/WILD.md", "\n".join(o) + "\n")
