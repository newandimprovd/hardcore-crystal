"""One-time (idempotent) registration of the generated tilesets in the vanilla tables, marked `; HC-ART`."""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
MARK = "; HC-ART"


def rd(p):
    return open(os.path.join(ROOT, p)).read()


def wr(p, s):
    open(os.path.join(ROOT, p), "w").write(s)


def register(tilesets):
    """tilesets: ordered list of Tileset objects (name 'Tithe', const 'TILESET_TITHE', stem 'tithe')."""
    # constants (the area tilesets come last, in this order; engine/hardcore/area_pals.asm relies on TILESET_TITHE being the first)
    s = rd("constants/tileset_constants.asm")
    start = s.index(f"\tconst TILESET_AERODACTYL_WORD_ROOM")
    end = s.index("DEF NUM_TILESETS EQU const_value - 1")
    head = s[:s.index("\n", start) + 1]
    block = "".join(f"\tconst {t.const} {MARK}\n" for t in tilesets)
    wr("constants/tileset_constants.asm", head + block + s[end:])
    # tileset table
    s = rd("data/tilesets.asm")
    s = "\n".join(l for l in s.split("\n") if MARK not in l)
    anchor = "\tassert_table_length NUM_TILESETS + 1"
    s = s.replace(anchor, "".join(f"\ttileset Tileset{t.name} {MARK}\n" for t in tilesets) + anchor)
    wr("data/tilesets.asm", s)
    # palette maps (must live in the same bank as the other maps)
    s = rd("gfx/tileset_palette_maps.asm")
    if MARK in s:
        s = s[:s.index(f"\n{MARK} begin")].rstrip("\n") + "\n"
    s += f"\n{MARK} begin\n" + "".join(
        f'Tileset{t.name}PalMap:\nINCLUDE "gfx/tilesets/{t.stem}_palette_map.asm"\n\n' for t in tilesets)
    wr("gfx/tileset_palette_maps.asm", s)
    # no animation: share the empty list of the other indoor tilesets
    s = rd("data/tileset_anims.asm")
    s = "\n".join(l for l in s.split("\n") if MARK not in l)
    anchor = "TilesetBattleTowerOutsideAnim:\n"
    assert anchor in s
    s = s.replace(anchor, anchor + "".join(f"Tileset{t.name}Anim: {MARK}\n" for t in tilesets))
    wr("data/tileset_anims.asm", s)
    # graphics, metatiles and collision in their own section
    o = ["; Generated by tools/hardcore/gen_tilesets.py. Do not edit by hand.\n", 'SECTION "Area Tilesets", ROMX\n']
    for t in tilesets:
        o.append(f'Tileset{t.name}GFX::\nINCBIN "gfx/tilesets/{t.stem}.2bpp.lz"\n')
        o.append(f'Tileset{t.name}Meta::\nINCBIN "data/tilesets/{t.stem}_metatiles.bin"\n')
        o.append(f'Tileset{t.name}Coll::\nINCLUDE "data/tilesets/{t.stem}_collision.asm"\n')
    wr("gfx/area_tilesets.asm", "\n".join(o))
    s = rd("main.asm")
    inc = f'INCLUDE "gfx/area_tilesets.asm" {MARK}\n'
    if inc in s:
        wr("main.asm", s.replace("\n" + inc, "").replace(inc, ""))
    s = rd("gfx/tilesets.asm")
    if inc not in s:
        wr("gfx/tilesets.asm", s.rstrip("\n") + "\n\n" + inc)
