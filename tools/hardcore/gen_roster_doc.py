#!/usr/bin/env python3
"""Writes docs/ROSTER.md from tools/hardcore/roster/roster_out.json (run after gen_roster.py)."""
import json
import os

root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
d = json.load(open(root + "/tools/hardcore/roster/roster_out.json"))
lines = {}
for r in d:
    lines.setdefault(r["line"], []).append(r)
out = []
out.append("# Roster (generated by tools/hardcore/gen_roster_doc.py, do not edit by hand)\n")
out.append(f"{len(d)} species in {len(lines)} lines. Every line has four stages: base, then evolutions at levels 25, 50 and 75.")
out.append("No branching, no single-stage species, no legendaries. Dratini and Larvitar lines are the strongest. "
           "Final stages carry +35 base HP. New species are marked with *.\n")
out.append("| ID | Species | Types | HP | Atk | Def | Spe | SpA | SpD | BST |")
out.append("|---|---|---|---|---|---|---|---|---|---|")
for k, st in lines.items():
    st.sort(key=lambda r: r["stage"])
    out.append(f"| | **{k} line** | | | | | | | | |")
    for r in st:
        t = r["types"][0] if r["types"][0] == r["types"][1] else "/".join(r["types"])
        s = r["stats"]
        out.append(f"| {r['id']} | {r['name']}{'*' if r['new'] else ''} (stage {r['stage']}) | {t} | "
                   + " | ".join(str(x) for x in s) + f" | {sum(s)} |")
open(root + "/docs/ROSTER.md", "w").write("\n".join(out) + "\n")
print("wrote docs/ROSTER.md", len(out), "rows")
