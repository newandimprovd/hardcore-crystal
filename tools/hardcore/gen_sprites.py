#!/usr/bin/env python3
"""Original overworld NPC sprites of the generated areas: draws the cast (tools/hardcore/art/cast.py + npcs.py), writes the png sheets
to gfx/sprites/hc/, the SPRITE_HC_* constants, the OverworldSprites rows and the GFX includes, and registers them once in the vanilla
tables (marked `; HC-ART`).  Run before gen_areas.py (the areas refer to the SPRITE_HC_* names).

Sprite id space: the vanilla human sprites end at SPRITE_CORPSE ($67); Pokemon icon sprites used to start at $80, so SPRITE_POKEMON is moved
up to $b0 to make room (const_next fails loudly if the generated sprites ever overflow that)."""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(HERE, "art"))
import npcs  # noqa: E402
from cast import CAST  # noqa: E402

MARK = "; HC-ART"
FIRST_MON_SPRITE = 0xB0


def camel(slug):
    return "".join(p.capitalize() for p in slug.split("_"))


def const(slug):
    return "SPRITE_HC_" + slug.upper()


def rd(p):
    return open(os.path.join(ROOT, p)).read()


def wr(p, s):
    full = os.path.join(ROOT, p)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    open(full, "w").write(s)


def main():
    os.makedirs(os.path.join(ROOT, "gfx/sprites/hc"), exist_ok=True)
    consts = ["; Generated by tools/hardcore/gen_sprites.py. Do not edit by hand."]
    rows = ["; Generated by tools/hardcore/gen_sprites.py. Do not edit by hand."]
    gfx = ["; Generated by tools/hardcore/gen_sprites.py. Do not edit by hand."]
    for n, (slug, rec) in enumerate(CAST.items()):
        if n % 30 == 0:  # 24 tiles = 384 bytes per sheet: 30 sheets fit a bank
            gfx += ["", f'SECTION "HC Sprites {n // 30 + 1}", ROMX', ""]
        npcs.write_png(rec, os.path.join(ROOT, f"gfx/sprites/hc/{slug}.png"))
        consts.append(f"\tconst {const(slug)}")
        gfx.append(f'Hc{camel(slug)}SpriteGFX:: INCBIN "gfx/sprites/hc/{slug}.2bpp"')
        rows.append(f"\toverworld_sprite Hc{camel(slug)}SpriteGFX, 12, STANDING_SPRITE, PAL_OW_BLUE")
    wr("constants/hc_sprite_constants.asm", "\n".join(consts) + "\n")
    wr("data/sprites/hc_sprites.asm", "\n".join(rows) + "\n")
    wr("gfx/hc_sprites.asm", "\n".join(gfx) + "\n")

    # one-time registration in the vanilla files
    s = rd("constants/sprite_constants.asm")
    inc = f'INCLUDE "constants/hc_sprite_constants.asm" {MARK}\n'
    if inc not in s:
        s = s.replace("DEF NUM_OVERWORLD_SPRITES EQU const_value - 1", inc + "DEF NUM_OVERWORLD_SPRITES EQU const_value - 1")
    s = re.sub(r"\tconst_next \$80\nDEF SPRITE_POKEMON", f"\tconst_next ${FIRST_MON_SPRITE:02x} {MARK}\nDEF SPRITE_POKEMON", s)
    assert f"const_next ${FIRST_MON_SPRITE:02x}" in s
    wr("constants/sprite_constants.asm", s)

    s = rd("data/sprites/sprites.asm")
    inc = f'INCLUDE "data/sprites/hc_sprites.asm" {MARK}\n'
    if inc not in s:
        s = s.replace("\tassert_table_length NUM_OVERWORLD_SPRITES", inc + "\tassert_table_length NUM_OVERWORLD_SPRITES")
    wr("data/sprites/sprites.asm", s)

    s = rd("gfx/sprites.asm")
    inc = f'INCLUDE "gfx/hc_sprites.asm" {MARK}\n'
    if inc not in s:
        wr("gfx/sprites.asm", s.rstrip("\n") + "\n\n" + inc)
    print(f"sprites: {len(CAST)} characters, ids ${0x68:02x}..${0x68 + len(CAST) - 1:02x}")
    assert 0x68 + len(CAST) <= FIRST_MON_SPRITE


if __name__ == "__main__":
    main()
