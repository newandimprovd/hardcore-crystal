#!/usr/bin/env python3
"""Registers the trainer classes of the generated areas (tools/hardcore/art/classes.py): constants, names, attributes, DVs, music, pics and palettes,
appended after the vanilla classes (marked `; HC-CLASSES`).  Run after gen_sprites.py and before gen_areas.py.  Idempotent."""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(HERE, "art"))
import classes  # noqa: E402
import npcs  # noqa: E402,F401
import portraits  # noqa: E402
from cast import CAST  # noqa: E402

BEGIN, END = "; HC-CLASSES begin", "; HC-CLASSES end"


def rd(p):
    return open(os.path.join(ROOT, p)).read()


def wr(p, s):
    full = os.path.join(ROOT, p)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    open(full, "w").write(s)


def strip(s):
    """Remove an earlier generated region."""
    return re.sub(r"[^\n]*" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"[^\n]*\n", "", s, flags=re.S)


def insert_before(s, anchor, block):
    assert s.count(anchor) == 1, (anchor, s.count(anchor))
    return s.replace(anchor, f"{BEGIN}\n{block}\n{END}\n{anchor}")


def vanilla_ids():
    ids = {}
    n = 0
    for l in rd("constants/trainer_constants.asm").split(BEGIN)[0].splitlines():
        m = re.match(r"\s*trainerclass (\w+)", l)
        if m:
            if m[1] != "TRAINER_NONE":
                n += 1
                ids[m[1]] = n
    return ids


def blocks_of(s, start_marker, end_marker):
    body = s[s.index(start_marker) + len(start_marker):s.index(end_marker)]
    return [b.strip("\n") for b in re.split(r"\n\s*\n", body.strip("\n")) if b.strip()]


def main():
    van = vanilla_ids()
    allc = [c for _, c in classes.ALL]
    # ---- pngs
    os.makedirs(os.path.join(ROOT, "gfx/trainers/hc"), exist_ok=True)
    for area, c in classes.ALL:
        const, label, slug, pal = c[0], c[1], c[2], c[3]
        portraits.portrait(CAST[slug], area, pal, os.path.join(ROOT, f"gfx/trainers/hc/{const.lower()}.png"))
    # ---- pics: the portraits are tiny after compression (about 65 bytes each), so they go into the free end of "Pics 20"
    o = ["; Generated by tools/hardcore/gen_classes.py. Do not edit by hand.", ""]
    for c in allc:
        o.append(f'Hc{c[0].title().replace("_", "")}Pic: INCBIN "gfx/trainers/hc/{c[0].lower()}.2bpp.lz"')
    wr("gfx/trainers/hc_pics.asm", "\n".join(o) + "\n")
    s = rd("gfx/pics.asm")
    inc = 'INCLUDE "gfx/trainers/hc_pics.asm" ; HC-ART\n'
    if inc not in s:
        sect = 'INCLUDE "gfx/pokemon/hc_pics.asm"\n'
        assert s.count(sect) == 1
        wr("gfx/pics.asm", s.replace(sect, sect + inc))
    # ---- constants
    s = strip(rd("constants/trainer_constants.asm"))
    n0 = max(van.values())
    lines = [f"\ttrainerclass {c[0]} ; {n0 + i + 1:02x}" for i, c in enumerate(allc)]
    s = insert_before(s, "DEF NUM_TRAINER_CLASSES EQU __trainer_class__ - 1", "\n".join(lines))
    wr("constants/trainer_constants.asm", s)
    # ---- names
    s = strip(rd("data/trainers/class_names.asm"))
    s = insert_before(s, "\tassert_list_length NUM_TRAINER_CLASSES", "\n".join(f'\tli "{c[1]}"' for c in allc))
    wr("data/trainers/class_names.asm", s)
    # ---- attributes (copied from the vanilla class)
    s = strip(rd("data/trainers/attributes.asm"))
    blks = blocks_of(s, "\ttable_width NUM_TRAINER_ATTRIBUTES", "\tassert_table_length NUM_TRAINER_CLASSES")
    assert len(blks) == len(van), (len(blks), len(van))
    new = []
    for c in allc:
        b = blks[van[c[5]] - 1].split("\n")
        b[0] = f"; {c[1].title()} ({c[0]})"
        new.append("\n".join(b))
    s = insert_before(s, "\tassert_table_length NUM_TRAINER_CLASSES", "\n" + "\n\n".join(new) + "\n")
    wr("data/trainers/attributes.asm", s)
    # ---- DVs
    s = strip(rd("data/trainers/dvs.asm"))
    dvs = [l for l in s.splitlines() if l.startswith("\tdn ")]
    assert len(dvs) == len(van)
    new = [re.sub(r";.*$", f"; {c[0]}", dvs[van[c[5]] - 1]) for c in allc]
    s = insert_before(s, "\tassert_table_length NUM_TRAINER_CLASSES", "\n".join(new))
    wr("data/trainers/dvs.asm", s)
    # ---- encounter music: the music table lives in the full "Audio" bank, so the new classes share one jingle (patched in audio/engine.asm)
    s = strip(rd("data/trainers/encounter_music.asm"))
    s = s.replace("\tassert_table_length NUM_TRAINER_CLASSES + 1\n", "\tassert_table_length T_COP ; HC-ART: only the vanilla classes have a row\n")
    wr("data/trainers/encounter_music.asm", s)
    a = rd("audio/engine.asm")
    old = "\tld d, $00\n\tld hl, TrainerEncounterMusic\n\tadd hl, de\n"
    if "HC-ART" not in a[a.index("PlayTrainerEncounterMusic::"):a.index("PlayTrainerEncounterMusic::") + 700]:
        assert a.count(old) == 1
        a = a.replace(old, "\tld a, e ; HC-ART: the generated trainer classes share one encounter jingle (the table is not extended)\n"
                      "\tcp T_COP ; HC-ART\n\tjr c, .vanilla_class ; HC-ART\n\tld e, OFFICER ; HC-ART\n.vanilla_class ; HC-ART\n" + old)
        wr("audio/engine.asm", a)
    # ---- Battle Tower genders and sprites (the vanilla tables exclude MYSTICALMAN, the last class; now it has a row too)
    for f, rows in (("genders", ["\tdb MALE ; MYSTICALMAN"] + [f"\tdb {c[6][:1] + c[6][1:].lower() if False else c[6]} ; {c[0]}" for c in allc]),
                    ("sprites", ["\tdb SPRITE_GRAMPS ; MYSTICALMAN"] + [f"\tdb {classes.sprite(c[2])} ; {c[0]}" for c in allc])):
        s = strip(rd(f"data/trainers/{f}.asm"))
        s = s.replace("\tassert_table_length NUM_TRAINER_CLASSES - 1 ; exclude MYSTICALMAN", "\tassert_table_length NUM_TRAINER_CLASSES")
        s = insert_before(s, "\tassert_table_length NUM_TRAINER_CLASSES", "\n".join(rows))
        wr(f"data/trainers/{f}.asm", s)
    # ---- palettes
    s = strip(rd("data/trainers/palettes.asm"))
    s = insert_before(s, "\tassert_table_length NUM_TRAINER_CLASSES + 1",
                      "\n".join(f'INCBIN "gfx/trainers/hc/{c[0].lower()}.gbcpal", middle_colors' for c in allc) + "\n")
    wr("data/trainers/palettes.asm", s)
    # ---- group pointers (generated trainers only, see engine/hardcore/gen_trainers.asm) and pic pointers
    s = strip(rd("data/trainers/party_pointers.asm"))
    s = insert_before(s, "\tassert_table_length NUM_TRAINER_CLASSES", "\n".join("\tdw HC_EmptyGroup" for _ in allc))
    wr("data/trainers/party_pointers.asm", s)
    s = rd("data/trainers/parties.asm")
    if "HC_EmptyGroup:" not in s:
        s = s.rstrip("\n") + "\n\nHC_EmptyGroup: ; HC-ART: the generated trainers (id >= HC_GEN_ID_BASE) live in data/hardcore/gen_trainer_data.asm\n\tdb -1 ; end\n"
        wr("data/trainers/parties.asm", s)
    s = strip(rd("data/trainers/pic_pointers.asm"))
    s = insert_before(s, "\tassert_table_length NUM_TRAINER_CLASSES",
                      "\n".join(f'\tdba_pic Hc{c[0].title().replace("_", "")}Pic' for c in allc))
    wr("data/trainers/pic_pointers.asm", s)
    lk = rd("layout.link")
    if "; HC-ART trainer pic pointers" not in lk:
        assert lk.count('ROMX $4a\n\t"Trainer Pic Pointers"\n\t"Pics 3"\n') == 1
        lk = lk.replace('ROMX $4a\n\t"Trainer Pic Pointers"\n\t"Pics 3"\n', 'ROMX $4a\n\t"Pics 3"\n')
        assert lk.count('ROMX $7c\n') == 1
        lk = lk.replace('ROMX $7c\n', 'ROMX $7c\n\t"Trainer Pic Pointers" ; HC-ART trainer pic pointers (moved out of the full bank $4a)\n')
        wr("layout.link", lk)
    print(f"classes: {len(allc)} new (ids {n0 + 1}..{n0 + len(allc)}), total {n0 + len(allc)}")
    assert n0 + len(allc) < 255


if __name__ == "__main__":
    main()
